import {joinStatements} from './render.ts';
import type {IndexSpec} from './spec.ts';

/**
 * What one migration changed: the indexes it created, recreated or repaired, and the ones it dropped.
 * Each migration records only its own changes, so migrations from two branches add up instead of overwriting each other.
 */
export type Marker = {
	readonly version: 1;
	readonly set: readonly IndexSpec[];
	/** The names in `set` this migration created, rather than changed or repaired. */
	readonly created: readonly string[];
	readonly drop: readonly string[];
};

const markerPrefix = '-- drizzle-sqlite-fts:state ';

/** The contents of a migration file: the statements, then the marker as a comment line on the last statement. */
export function renderMigration(statements: readonly string[], marker: Marker): string {
	const header = '-- Generated by drizzle-sqlite-fts from your fts5() declarations.';
	return `${header}\n${joinStatements(statements)}\n${markerPrefix}${JSON.stringify(marker)}\n`;
}

const isStringArray = (value: unknown): value is string[] => Array.isArray(value) && value.every(item => typeof item === 'string');

const isOptional = (value: unknown, check: (value: unknown) => boolean): boolean => value === undefined || check(value);

function hasValidOptions(spec: Partial<IndexSpec>): boolean {
	return isOptional(spec.tokenize, value => typeof value === 'string')
		&& isOptional(spec.prefix, value => Array.isArray(value) && value.every(length => Number.isInteger(length)))
		&& isOptional(spec.detail, value => value === 'full' || value === 'column' || value === 'none')
		&& isOptional(spec.columnsize, value => typeof value === 'boolean');
}

function isIndexSpec(value: unknown): value is IndexSpec {
	const spec = value as Partial<IndexSpec> | null;
	if (typeof spec !== 'object' || spec === null || typeof spec.name !== 'string' || spec.name === ''
		|| !isStringArray(spec.columns) || spec.columns.length === 0 || !hasValidOptions(spec)) {
		return false;
	}

	const content = spec.content as Partial<NonNullable<IndexSpec['content']>> | undefined;
	return spec.mode === 'external'
		? typeof content?.table === 'string' && typeof content.rowid === 'string'
		: (spec.mode === 'contentless' || spec.mode === 'standalone') && content === undefined;
}

function isMarker(value: unknown): value is Marker {
	const marker = value as Partial<Marker> | null;
	return typeof marker === 'object' && marker !== null && marker.version === 1
		&& Array.isArray(marker.set) && marker.set.every(isIndexSpec) && isStringArray(marker.created) && isStringArray(marker.drop);
}

/** The text after the last marker that starts a line. */
function markerText(migration: string): string | undefined {
	const lineIndex = migration.lastIndexOf(`\n${markerPrefix}`);
	const start = lineIndex === -1 ? (migration.startsWith(markerPrefix) ? 0 : -1) : lineIndex + 1;
	if (start === -1) {
		return undefined;
	}

	const end = migration.indexOf('\n', start);
	return migration.slice(start + markerPrefix.length, end === -1 ? undefined : end).trimEnd();
}

/** The marker in a migration file, or `undefined` for a migration drizzle-sqlite-fts didn't write. */
export function readMarker(migration: string): Marker | undefined {
	const text = markerText(migration);
	if (text === undefined) {
		return undefined;
	}

	let marker: unknown;
	try {
		marker = JSON.parse(text);
	} catch {
		marker = undefined;
	}

	if (!isMarker(marker)) {
		throw new Error(`Unsupported drizzle-sqlite-fts state, was the migration edited by hand or written by a newer version? ${text.slice(0, 200)}`);
	}

	return marker;
}
