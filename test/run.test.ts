import assert from 'node:assert/strict';
import {existsSync, mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {test, type TestContext} from 'node:test';
import {collectDefinitions, runCli, usage, type CliEnvironment} from '../src/cli/run.ts';
import {fts5, getFts5Definition} from '../src/declare.ts';
import {readMarker} from '../src/migration.ts';
import {articles, notes} from './fixtures.ts';
import {temporaryProject} from './helpers.ts';

const notesSearch = fts5('notes_fts', {table: notes, columns: ['title', 'body']});
const memo = fts5('memo', {mode: 'contentless', columns: ['text']});
const createNotes = 'CREATE TABLE `notes` (\n\t`id` integer PRIMARY KEY NOT NULL,\n\t`title` text NOT NULL,\n\t`body` text\n);';

type FakeOptions = {
	readonly config?: unknown;
	readonly schema?: Record<string, unknown>;
	/** Folder names drizzle-kit creates, one per call. */
	readonly createdFolders?: string[];
	readonly drizzleKitStatus?: number;
};

function fakeEnvironment(t: TestContext, options: FakeOptions = {}) {
	const cwd = temporaryProject(t, {'drizzle.config.ts': '', 'schema.ts': '', 'drizzle/20261030115959_init/migration.sql': createNotes});
	const output: string[] = [];
	const errors: string[] = [];
	const drizzleKitCalls: (readonly string[])[] = [];
	const sleeps: number[] = [];
	const createdFolders = [...(options.createdFolders ?? ['20261030120000_fts', '20261030120001_fts', '20261030120002_fts'])];
	const environment: CliEnvironment = {
		cwd,
		print: text => output.push(text),
		printError: text => errors.push(text),
		importModule: async file => (file.endsWith('drizzle.config.ts')
			? options.config ?? {default: {dialect: 'sqlite', schema: './schema.ts'}}
			: options.schema ?? {notes, notesSearch}),
		runDrizzleKit(args) {
			drizzleKitCalls.push(args);
			const folder = path.join(cwd, 'drizzle', createdFolders.shift()!);
			mkdirSync(folder, {recursive: true});
			writeFileSync(path.join(folder, 'migration.sql'), '-- Custom SQL migration file, put your code below! --\n');
			return options.drizzleKitStatus ?? 0;
		},
		sleep: async milliseconds => {
			sleeps.push(milliseconds);
		},
	};
	return {cwd, environment, output, errors, drizzleKitCalls, sleeps};
}

const firstMigration = path.join('drizzle', '20261030120000_fts', 'migration.sql');

test('collectDefinitions finds each fts5() export once', () => {
	const definitions = collectDefinitions([{notes, notesSearch, again: notesSearch, label: 'notes', nothing: null}, {memo}]);
	assert.deepEqual(definitions, [getFts5Definition(notesSearch), getFts5Definition(memo)]);
});

test('runCli prints the usage for --help, and fails without a command', async t => {
	const {environment, output} = fakeEnvironment(t);
	assert.equal(await runCli(['--help'], environment), 0);
	assert.equal(await runCli(['generate', '-h'], environment), 0);
	assert.equal(await runCli([], environment), 1);
	assert.deepEqual(output, [usage, usage, usage]);
});

test('runCli rejects unknown commands and options', async t => {
	const {environment, errors} = fakeEnvironment(t);
	assert.equal(await runCli(['push'], environment), 1);
	assert.match(errors[0]!, /^Unknown command push\n\nUsage:/);
	assert.equal(await runCli(['generate', '--force'], environment), 1);
	assert.match(errors[1]!, /^drizzle-sqlite-fts: Unknown option '--force'/);
});

test('generate writes the migration into the file drizzle-kit creates, then has nothing to do', async t => {
	const {cwd, environment, output, drizzleKitCalls} = fakeEnvironment(t);
	assert.equal(await runCli(['generate', '--name', 'search'], environment), 0);
	assert.deepEqual(drizzleKitCalls, [['generate', '--custom', '--name=search', `--config=${path.join(cwd, 'drizzle.config.ts')}`]]);
	const migration = readFileSync(path.join(cwd, firstMigration), 'utf8');
	assert.match(migration, /^-- Generated by drizzle-sqlite-fts[^\n]*\nCREATE VIRTUAL TABLE IF NOT EXISTS "notes_fts" USING fts5/);
	assert.deepEqual(readMarker(migration)?.created, ['notes_fts']);
	assert.deepEqual(output, [`Wrote ${firstMigration}:\n  - create notes_fts`]);

	assert.equal(await runCli(['generate'], environment), 0);
	assert.equal(drizzleKitCalls.length, 1);
	assert.equal(output[1], 'No FTS5 index changes, nothing to generate.');
});

test('generate tries again when the new migration would not run last', async t => {
	const {cwd, environment, sleeps, drizzleKitCalls} = fakeEnvironment(t, {createdFolders: ['20261030115959_aaa', '20261030120001_fts']});
	assert.equal(await runCli(['generate'], environment), 0);
	assert.equal(drizzleKitCalls.length, 2);
	assert.deepEqual(sleeps, [1000]);
	assert.ok(!existsSync(path.join(cwd, 'drizzle/20261030115959_aaa')));
	assert.match(readFileSync(path.join(cwd, 'drizzle/20261030120001_fts/migration.sql'), 'utf8'), /drizzle-sqlite-fts:state/);
});

test('generate gives up when the new migration keeps sorting first', async t => {
	const {environment, errors} = fakeEnvironment(t, {createdFolders: ['1_a', '1_b', '1_c']});
	assert.equal(await runCli(['generate'], environment), 1);
	assert.deepEqual(errors, ['Could not create a migration that sorts after the existing ones in 3 attempts']);
});

test('generate reports a failing drizzle-kit and an unexpected number of new files', async t => {
	const failing = fakeEnvironment(t, {drizzleKitStatus: 3});
	assert.equal(await runCli(['generate'], failing.environment), 3);
	assert.deepEqual(failing.errors, ['drizzle-kit generate --custom failed with exit code 3']);

	const silent = fakeEnvironment(t);
	const environment = {...silent.environment, runDrizzleKit: () => 0};
	assert.equal(await runCli(['generate'], environment), 1);
	assert.deepEqual(silent.errors, ['drizzle-sqlite-fts: Expected drizzle-kit to create one migration, found 0']);
});

test('generate and check refuse with exit code 2 and write nothing', async t => {
	const {cwd, environment, errors, drizzleKitCalls} = fakeEnvironment(t, {schema: {articles, search: fts5('articles_fts', {table: articles, columns: ['headline']})}});
	assert.equal(await runCli(['generate'], environment), 2);
	assert.equal(await runCli(['check'], environment), 2);
	const refusal = 'Nothing was written, because:\n  - "articles_fts" indexes "articles", which no earlier migration creates. Run drizzle-kit generate first, then run this again.';
	assert.deepEqual(errors, [refusal, refusal]);
	assert.deepEqual(drizzleKitCalls, []);
	assert.ok(!existsSync(path.join(cwd, firstMigration)));
});

test('a change that loses rows needs --allow-data-loss', async t => {
	const {cwd, environment, errors, output} = fakeEnvironment(t, {schema: {memo}});
	assert.equal(await runCli(['generate'], environment), 0);
	const changed = fts5('memo', {mode: 'contentless', columns: ['text'], tokenize: 'trigram'});
	const next = {...environment, importModule: async (file: string) => (file.endsWith('schema.ts') ? {changed} : environment.importModule(file))};
	assert.equal(await runCli(['generate'], next), 2);
	assert.match(errors[0]!, /Changing "memo" recreates it empty/);
	assert.equal(await runCli(['generate', '--allow-data-loss'], next), 0);
	assert.equal(output.at(-1), `Wrote ${path.join('drizzle', '20261030120001_fts', 'migration.sql')}:\n  - recreate memo`);
	assert.match(readFileSync(path.join(cwd, 'drizzle/20261030120001_fts/migration.sql'), 'utf8'), /tokenize='trigram'/);
});

test('check passes when the migrations are up to date and fails otherwise', async t => {
	const {environment, output, errors} = fakeEnvironment(t);
	assert.equal(await runCli(['check'], environment), 1);
	assert.equal(errors[0], 'FTS5 indexes changed without a migration. Run drizzle-sqlite-fts generate to:\n  - create notes_fts');
	await runCli(['generate'], environment);
	assert.equal(await runCli(['check', '--config', 'drizzle.config.ts'], environment), 0);
	assert.equal(output.at(-1), 'FTS5 indexes match the migrations.');
});

test('sql prints statements that create every index from scratch', async t => {
	const {environment, output} = fakeEnvironment(t, {schema: {notesSearch, memo}});
	assert.equal(await runCli(['sql'], environment), 0);
	assert.match(output[0]!, /^CREATE VIRTUAL TABLE IF NOT EXISTS "notes_fts" USING fts5[\s\S]+\n\nINSERT INTO "notes_fts"\("notes_fts"\) VALUES \('rebuild'\);\n\nCREATE VIRTUAL TABLE IF NOT EXISTS "memo"/);
});

test('runCli reports configuration errors', async t => {
	const noSchema = fakeEnvironment(t, {config: {default: {dialect: 'sqlite', schema: './src/*.ts'}}});
	assert.equal(await runCli(['sql'], noSchema.environment), 1);
	assert.deepEqual(noSchema.errors, ['drizzle-sqlite-fts: No schema files match ./src/*.ts']);

	const postgres = fakeEnvironment(t, {config: {default: {dialect: 'postgresql', schema: './schema.ts'}}});
	assert.equal(await runCli(['check'], postgres.environment), 1);
	assert.match(postgres.errors[0]!, /^drizzle-sqlite-fts: drizzle-sqlite-fts supports the 'sqlite', 'turso', 'd1-http' dialects only, got "postgresql"/);

	const noConfig = fakeEnvironment(t);
	assert.equal(await runCli(['sql', '-c', 'other.ts'], noConfig.environment), 1);
	assert.match(noConfig.errors[0]!, /^drizzle-sqlite-fts: No drizzle config found: looked for other.ts in /);
});

test('runCli reports a schema file that throws something other than an Error', async t => {
	const {environment, errors} = fakeEnvironment(t);
	const failing: CliEnvironment = {...environment, importModule: async file => {
		if (file.endsWith('schema.ts')) {
			throw 'schema.ts: unexpected token';
		}

		return environment.importModule(file);
	}};
	assert.equal(await runCli(['sql'], failing), 1);
	assert.deepEqual(errors, ['drizzle-sqlite-fts: schema.ts: unexpected token']);
});
