import assert from 'node:assert/strict';
import {test} from 'node:test';
import {readMarker, renderMigration, type Marker} from '../src/migration.ts';
import {recordedIndexes} from '../src/state.ts';
import type {IndexSpec} from '../src/spec.ts';

const notesSpec: IndexSpec = {name: 'notes_fts', mode: 'external', columns: ['title'], content: {table: 'notes', rowid: 'id'}};
const docsSpec: IndexSpec = {name: 'docs', mode: 'standalone', columns: ['title'], prefix: [2]};
const marker = (set: IndexSpec[], drop: string[] = [], created: string[] = []): Marker => ({version: 1, set, created, drop});
/** A marker for a migration that creates every index it sets. */
const creating = (set: IndexSpec[]): Marker => marker(set, [], set.map(spec => spec.name));

test('a migration ends with its marker, which reads back unchanged', () => {
	const migration = renderMigration(['CREATE TABLE a (b);', 'DROP TABLE c;'], marker([notesSpec, docsSpec], ['old']));
	assert.equal(migration, [
		'-- Generated by drizzle-sqlite-fts from your fts5() declarations.',
		'CREATE TABLE a (b);',
		'--> statement-breakpoint',
		'DROP TABLE c;',
		`-- drizzle-sqlite-fts:state ${JSON.stringify(marker([notesSpec, docsSpec], ['old']))}`,
		'',
	].join('\n'));
	assert.deepEqual(readMarker(migration), marker([notesSpec, docsSpec], ['old']));
});

test('a migration without a marker has none, and a marker can open the file', () => {
	assert.equal(readMarker('CREATE TABLE notes (id integer);'), undefined);
	assert.equal(readMarker(''), undefined);
	assert.deepEqual(readMarker(`-- drizzle-sqlite-fts:state ${JSON.stringify(marker([]))}`), marker([]));
	assert.deepEqual(readMarker(`-- drizzle-sqlite-fts:state ${JSON.stringify(marker([]))}\n-- drizzle-sqlite-fts:state ${JSON.stringify(marker([docsSpec]))}`), marker([docsSpec]));
});

test('a marker that is not one this version wrote is an error', () => {
	const bad = [
		'not json',
		'{"version":2,"set":[],"created":[],"drop":[]}',
		'{"version":1,"set":[],"created":[],"drop":[1]}',
		'{"version":1,"set":[],"drop":[]}',
		'{"version":1,"set":{},"created":[],"drop":[]}',
		'null',
		'{"version":1,"set":[null],"created":[],"drop":[]}',
		'{"version":1,"set":[{"name":"a","mode":"external","columns":["b"]}],"created":[],"drop":[]}',
		'{"version":1,"set":[{"name":"a","mode":"standalone","columns":["b"],"content":{"table":"t","rowid":"id"}}],"created":[],"drop":[]}',
		'{"version":1,"set":[{"name":"a","mode":"other","columns":["b"]}],"created":[],"drop":[]}',
		'{"version":1,"set":[{"name":"a","mode":"standalone","columns":"b"}],"created":[],"drop":[]}',
		'{"version":1,"set":[{"name":"","mode":"standalone","columns":["b"]}],"created":[],"drop":[]}',
		'{"version":1,"set":[{"name":"a","mode":"standalone","columns":[]}],"created":[],"drop":[]}',
		'{"version":1,"set":[{"name":"a","mode":"standalone","columns":["b"],"tokenize":1}],"created":[],"drop":[]}',
		'{"version":1,"set":[{"name":"a","mode":"standalone","columns":["b"],"prefix":"x"}],"created":[],"drop":[]}',
		'{"version":1,"set":[{"name":"a","mode":"standalone","columns":["b"],"prefix":[1.5]}],"created":[],"drop":[]}',
		'{"version":1,"set":[{"name":"a","mode":"standalone","columns":["b"],"detail":"some"}],"created":[],"drop":[]}',
		'{"version":1,"set":[{"name":"a","mode":"standalone","columns":["b"],"columnsize":"no"}],"created":[],"drop":[]}',
	];
	for (const text of bad) {
		assert.throws(() => readMarker(`SELECT 1;\n-- drizzle-sqlite-fts:state ${text}\n`), /Unsupported drizzle-sqlite-fts state/);
	}
});

test('markers fold in migration order, so two branches each adding an index keep both', () => {
	const branchA = renderMigration([], creating([notesSpec]));
	const branchB = renderMigration([], creating([docsSpec]));
	const recorded = recordedIndexes(['CREATE TABLE notes (id integer);', branchA, branchB]);
	assert.deepEqual([...recorded.indexes.entries()], [['notes_fts', {spec: notesSpec, migration: 1}], ['docs', {spec: docsSpec, migration: 2}]]);
	assert.deepEqual(recorded.conflicts, []);
});

test('a later marker replaces an index and a drop removes it, whatever the letter case', () => {
	const changed = {...docsSpec, name: 'Docs', tokenize: 'trigram'};
	const recorded = recordedIndexes([
		renderMigration([], creating([notesSpec, docsSpec])),
		renderMigration([], marker([changed])),
		renderMigration([], marker([], ['NOTES_FTS'])),
	]);
	assert.deepEqual([...recorded.indexes.entries()], [['docs', {spec: changed, migration: 1}]]);
	assert.deepEqual(recorded.conflicts, []);
});

test('two branches creating one index with different settings conflict, and the first one is what is recorded', () => {
	const wider = {...docsSpec, columns: ['title', 'body']};
	const recorded = recordedIndexes([renderMigration([], creating([docsSpec])), renderMigration([], creating([wider]))]);
	assert.deepEqual([...recorded.indexes.values()], [{spec: docsSpec, migration: 0}]);
	assert.deepEqual(recorded.conflicts, [{name: 'docs', kind: 'created twice'}]);
	const same = recordedIndexes([renderMigration([], creating([docsSpec])), renderMigration([], creating([{...docsSpec, name: 'DOCS'}]))]);
	assert.deepEqual(same.conflicts, [], 'the same index created twice is no conflict');
});

test('a branch changing an index another branch dropped conflicts', () => {
	const recorded = recordedIndexes([
		renderMigration([], creating([docsSpec])),
		renderMigration([], marker([], ['docs'])),
		renderMigration([], marker([{...docsSpec, tokenize: 'trigram'}])),
	]);
	assert.deepEqual(recorded.indexes.size, 0);
	assert.deepEqual(recorded.conflicts, [{name: 'docs', kind: 'changed after drop'}]);
});
